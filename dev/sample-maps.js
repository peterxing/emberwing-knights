const check = (m) => {
  if (m.tiles.length !== m.height) throw new Error(`${m.id}: ${m.tiles.length} rows, expected ${m.height}`);
  m.tiles.forEach((r, i) => { if (r.length !== m.width) throw new Error(`${m.id}: row ${i} has ${r.length} chars`); });
  if (m.heights) m.heights.forEach((r, i) => { if (r.length !== m.width) throw new Error(`${m.id}: heights row ${i} has ${r.length} chars`); });
  return m;
};

